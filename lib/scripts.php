/**
 * Component assets (Tailwind CSS and JavaScript)
 * Loads on pages using template-components.php OR case studies/posts with Flexible Components template
 * Conditionally loads component-specific JS based on what's used
 * Handles both regular components and nested global_components
 */
function enqueue_component_assets() {
    $load_components = false;
    
    if ( is_page_template('template-components.php') ) {
        $load_components = true;
    } elseif ( is_singular('case_studies') ) {
        $post_id = get_queried_object_id();
        if ( get_post_meta($post_id, 'case_study_template', true) === 'template-components.php' ) {
            $load_components = true;
        }
    } elseif ( is_singular('post') ) {
        $post_id = get_queried_object_id();
        if ( get_post_meta($post_id, 'post_template', true) === 'template-components.php' ) {
            $load_components = true;
        }
    }
    
    if ( !$load_components ) {
        return;
    }
    
    // Tailwind CSS for components (always needed)
    wp_enqueue_style(
        'components-css',
        get_template_directory_uri() . '/css/components.css',
        array(),
        '1.0.0'
    );
    
    // Detect which components are used
    $components_used = array();
    
    if( have_rows('flexible_components') ){
        while( have_rows('flexible_components') ){
            the_row();
            $layout = get_row_layout();
            
            // Check if this is a global_components wrapper
            if( $layout === 'global_components' ){
                // Get the selected component from the 'components' field
                $global_component = get_sub_field('components');
                if( $global_component ){
                    // Store with 'global_' prefix to distinguish from regular components
                    $components_used[] = 'global_' . $global_component;
                }
            } else {
                // Regular component
                $components_used[] = $layout;
            }
        }
        
        // Reset the loop (important for template rendering)
        reset_rows();
    }
    
    // Remove duplicates
    $components_used = array_unique($components_used);
    
    // Map component names to their JS files
    // Handles both regular and global components
    $component_scripts = array(
        // Regular components
        'faqs' => 'faqs',
        'video_player' => 'video',
        'contact_form' => 'form',
        'product_detail' => 'product-detail',
        'product_feature_carousel' => 'carousel',
        'recommended_products' => 'carousel',
        'vertical_tabs' => 'vertical-tabs',
        'vertical_carousel' => 'vertical-carousel',
        'application_cards' => 'application-cards',
        'testimonial_grid' => 'testimonials',
        
        // Global components (note the 'global_' prefix)
        'global_customer_carousel' => 'carousel',
        'global_partner_carousel' => 'carousel',
        'global_success_stories' => 'carousel',
        'global_latest_resources' => 'carousel',
        'global_solutions' => 'solutions',
        'global_testimonials' => 'testimonials',
        // Add more global components as needed when they require JS
    );
    
    // Enqueue only the scripts needed
    $scripts_to_load = array();
    foreach( $components_used as $component ){
        if( isset($component_scripts[$component]) ){
            $script_name = $component_scripts[$component];
            if( !in_array($script_name, $scripts_to_load) ){
                $scripts_to_load[] = $script_name;
            }
        }
    }
    
    // Ensure jQuery is loaded (WordPress default)
    wp_enqueue_script('jquery');
    
    // Check if vertical_carousel is used and enqueue GSAP libraries
    if (in_array('vertical_carousel', $components_used)) {
        // Enqueue GSAP core library
        wp_enqueue_script(
            'gsap',
            'https://cdn.jsdelivr.net/npm/gsap@3.12.5/dist/gsap.min.js',
            array(),
            '3.12.5',
            true
        );
        
        // Enqueue ScrollTrigger plugin
        wp_enqueue_script(
            'gsap-scrolltrigger',
            'https://cdn.jsdelivr.net/npm/gsap@3.12.5/dist/ScrollTrigger.min.js',
            array('gsap'),
            '3.12.5',
            true
        );
    }
    
    // Note: Slick Carousel is already bundled in global-scripts.min.js (loaded as 'scripts_js')
    // We don't need to load it again - just ensure scripts_js is a dependency for carousel components
    
    // Enqueue component-specific scripts
    foreach( $scripts_to_load as $script ){
        $dependencies = array('jquery');
        
        // If carousel/product-detail, depend on scripts_js (which contains Slick)
        if ($script === 'carousel' || $script === 'product-detail') {
            $dependencies[] = 'scripts_js'; // Use existing handle instead of loading duplicate
        }
        
        // If vertical-carousel, depend on GSAP libraries
        if ($script === 'vertical-carousel') {
            $dependencies[] = 'gsap-scrolltrigger';
        }
        
        wp_enqueue_script(
            'component_' . $script,
            get_template_directory_uri() . '/js/components/' . $script . '.js',
            $dependencies,
            '1.0.0',
            true
        );
    }
}
add_action('wp_enqueue_scripts', 'enqueue_component_assets');

